import java.util.*;
public class vowel {
    public static void main(String[] args) {
        Scanner sc=new Scanner(System.in);
        char ch=sc.next().charAt(0);
        if(ch=='a'){
            System.out.println("it  is vowel");
        }
        else if(ch=='e'){
            System.out.println("it is vowel");
        }
        else if(ch=='i'){
            System.out.println("it is vowel");
        }
        else if(ch=='o'){
            System.out.println("it is vowel");
        }
        else if(ch=='u'){
            System.out.println("it is vowel");
        }
        else{
          System.out.println("it is not a vowel");  
        }
    }

}
